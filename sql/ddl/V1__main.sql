create table google_conference (
    id bigint generated by default as identity,
    event_id varchar(255) not null unique,
    organizer_email varchar(255) not null,
    room_id varchar(255) not null,
    status varchar(255) not null check ((status in ('ACTIVE','PENDING','CANCELLED'))),
    primary key (id)
);

create table principal (
    is_managed boolean not null,
    id bigint generated by default as identity,
    email varchar(255) not null unique,
    name varchar(255),
    primary key (id)
);

create table server (
    id bigint generated by default as identity,
    owner_id bigint not null unique,
    name varchar(255) not null unique,
    server_type varchar(255) not null check ((server_type in ('CUSTOM','DEFAULT'))),
    server_url varchar(255) not null unique,
    primary key (id)
);

