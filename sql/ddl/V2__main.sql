
    create table google_conference (
        id bigint generated by default as identity,
        event_id varchar(255) not null unique,
        user_id bigint not null,
        server_id bigint not null,
        room_id varchar(255) not null,
        status varchar(255) not null check ((status in ('ACTIVE','PENDING','CANCELLED'))),
        primary key (id)
    );

    create table principal (
        is_managed boolean not null,
        id bigint generated by default as identity,
        email varchar(255) not null unique,
        name varchar(255),
        primary key (id)
    );

    create table server (
        id bigint generated by default as identity,
        user_id bigint,
        name varchar(255) not null,
        server_type varchar(255) not null check ((server_type in ('CUSTOM','DEFAULT'))),
        server_url varchar(255) not null,
        primary key (id),
        constraint uk_user_server unique (user_id, server_url)
    );
