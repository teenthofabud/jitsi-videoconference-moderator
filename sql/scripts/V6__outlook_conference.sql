CREATE TABLE outlook_conference (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_tracking_id varchar(255) NOT NULL UNIQUE,
    event_id varchar(255) UNIQUE,
    user_id bigint NOT NULL,
    server_id bigint NOT NULL,
    room_id varchar(255) NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('ACTIVE', 'PENDING', 'CANCELLED')),
    version bigint NOT NULL DEFAULT 0,
    last_modified_date timestamp with time zone NOT NULL DEFAULT now()
);
