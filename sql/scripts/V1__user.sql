-- Create Server Manager Role safely
DO $$
BEGIN
  CREATE ROLE ${SERVER_MANAGER_ROLE_NAME};
EXCEPTION WHEN duplicate_object THEN
  RAISE NOTICE 'Role ${SERVER_MANAGER_ROLE_NAME} already exists, skipping...';
END $$;

-- Grant DML (Read/Write) privileges on CURRENT objects
GRANT USAGE ON SCHEMA ${MODERATOR_SCHEMA_NAME} TO ${SERVER_MANAGER_ROLE_NAME};
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA ${MODERATOR_SCHEMA_NAME} TO ${SERVER_MANAGER_ROLE_NAME};
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA ${MODERATOR_SCHEMA_NAME} TO ${SERVER_MANAGER_ROLE_NAME};

-- Grant DML (Read/Write) privileges on FUTURE objects created by Flyway
ALTER DEFAULT PRIVILEGES FOR ROLE ${FLYWAY_USER} IN SCHEMA ${MODERATOR_SCHEMA_NAME}
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${SERVER_MANAGER_ROLE_NAME};

ALTER DEFAULT PRIVILEGES FOR ROLE ${FLYWAY_USER} IN SCHEMA ${MODERATOR_SCHEMA_NAME}
GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO ${SERVER_MANAGER_ROLE_NAME};

-- Create the application user safely
DO $$
BEGIN
  CREATE USER ${MODERATOR_DB_USERNAME} LOGIN PASSWORD '${MODERATOR_DB_PASSWORD}';
EXCEPTION WHEN duplicate_object THEN
  RAISE NOTICE 'User ${MODERATOR_DB_USERNAME} already exists, skipping...';
END $$;

-- Assign the DML role to the application user
GRANT ${SERVER_MANAGER_ROLE_NAME} TO ${MODERATOR_DB_USERNAME};
