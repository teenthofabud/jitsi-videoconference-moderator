#!/usr/bin/env bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE DATABASE ${MODERATOR_DB_NAME};

  \connect ${MODERATOR_DB_NAME}

  CREATE SCHEMA IF NOT EXISTS ${MODERATOR_SCHEMA_NAME};

  -- Flyway start --

  -- Create Migrator Role
  CREATE ROLE ${MIGRATOR_ROLE_NAME} WITH CREATEROLE;

  GRANT ALL PRIVILEGES ON SCHEMA ${MODERATOR_SCHEMA_NAME} TO ${MIGRATOR_ROLE_NAME};
  GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA ${MODERATOR_SCHEMA_NAME} TO ${MIGRATOR_ROLE_NAME};
  ALTER DEFAULT PRIVILEGES IN SCHEMA ${MODERATOR_SCHEMA_NAME} GRANT ALL PRIVILEGES ON TABLES TO ${MIGRATOR_ROLE_NAME};
  GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA ${MODERATOR_SCHEMA_NAME} TO ${MIGRATOR_ROLE_NAME};
  ALTER DEFAULT PRIVILEGES IN SCHEMA ${MODERATOR_SCHEMA_NAME} GRANT ALL PRIVILEGES ON SEQUENCES TO ${MIGRATOR_ROLE_NAME};

  -- Create Flyway migration user
  CREATE USER ${FLYWAY_USER} LOGIN PASSWORD '${FLYWAY_PASSWORD}' CREATEROLE;

  -- Assign role
  GRANT ${MIGRATOR_ROLE_NAME} TO ${FLYWAY_USER};
  -- Flyway end --
EOSQL
