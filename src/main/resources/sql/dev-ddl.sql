
    create table google_conference (
        id bigint generated by default as identity,
        server_preference_id bigint not null,
        event_id varchar(255) not null,
        room_id varchar(255) not null unique,
        status enum ('ACTIVE','INACTIVE') not null,
        primary key (id)
    );

    create table principal (
        id bigint generated by default as identity,
        name varchar(255) not null,
        subject varchar(255) not null unique,
        subject_hash varchar(255) not null unique,
        reference_type enum ('EMAIL') not null,
        primary key (id)
    );

    create table server (
        id bigint generated by default as identity,
        name varchar(255) not null unique,
        server_url varchar(255) not null unique,
        primary key (id)
    );

    create table server_preference (
        id bigint generated by default as identity,
        server_id bigint,
        server_url varchar(255) not null,
        user_id_hash varchar(255) not null unique,
        server_preference_type enum ('CUSTOM','DEFAULT'),
        primary key (id)
    );

