
    create table google_conference (
        created_by bigint,
        id bigint generated by default as identity,
        server_id bigint,
        event_id varchar(255) not null unique,
        room_id varchar(255) not null,
        status varchar(255) not null check (status in ('ACTIVE','PENDING','CANCELLED')),
        primary key (id)
    );

    create table principal (
        id bigint generated by default as identity,
        preferred_server_id bigint,
        email varchar(255) not null unique,
        name varchar(255) not null,
        reference_type varchar(255) not null check (reference_type in ('EMAIL')),
        primary key (id)
    );

    create table server (
        id bigint generated by default as identity,
        name varchar(255) not null unique,
        server_type varchar(255) not null check (server_type in ('CUSTOM','DEFAULT')),
        server_url varchar(255) not null unique,
        primary key (id)
    );

